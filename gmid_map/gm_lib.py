    target_idw = 10
    target_l = 1e-6
    L_list = np.array(list(ft_lutp.keys()))
    l = L_list[np.argmin(np.abs(L_list - target_l))]
    best_loss = np.inf
    for gmid in list(ft_lutp[l].keys()):
        if np.abs(target_idw - idw_lutp[l][gmid]) < best_loss:
            best_loss = np.abs(target_idw - idw_lutp[l][gmid])
            best_gmid = gmid
    ro = ro_lutp[l][best_gmid]
    # print('ro_all_target', ro_all_target)
    # print('ro', ro)
    ro_target = ro_all_target * ro / (ro - ro_all_target)
    idro_target = ro_target * id
    # print('ro_target', ro_target)
    # print('id', id)
    # print('idro_target', idro_target)
    # gmid_list = ft_lut.index.values.tolist()
    # print('gmid_list', gmid_list)
