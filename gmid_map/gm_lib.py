    # L_list = list(ft_lut.keys())
    # for l in L_list:
    best_l = l
    for gmid in list(ft_lutn[l].keys()):
        if np.abs(idro_target - ro_lutn[l][gmid] / gmid) < best_loss:
            best_loss = np.abs(idro_target - ro_lutn[l][gmid] / gmid)
            best_gmid = gmid
    w = id / idw_lutn[best_l][best_gmid]
    # print('best_gmid', best_gmid)
    # print('best_l', best_l)
    return w, best_l


